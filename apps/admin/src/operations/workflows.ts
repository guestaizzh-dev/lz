export function workflowForPage(path: string) {
  return workflows.find(workflow => workflow.steps.some(step => step.path === path));
}

export function matchesWorkflow(workflow: Workflow, query: string) {
  const text = [workflow.title, workflow.category, workflow.audience, workflow.summary, workflow.prepare,
    ...workflow.steps.map(step => step.title + step.detail), workflow.verify, ...workflow.cautions].join(' ');
  return text.toLocaleLowerCase().includes(query.trim().toLocaleLowerCase());
}
